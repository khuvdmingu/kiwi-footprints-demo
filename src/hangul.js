// 글자 하나 → { w, strokes } (모르는 글자는 빈칸 폭만 차지하고 그리지 않는다)
export function glyph(ch) {
  const s = syllableStrokes(ch);
  if (s) return { w: 1, strokes: s };
  const j = jamoStrokes(ch);
  if (j) return { w: 1, strokes: j };
  const L = LATIN[/[a-z]/.test(ch) ? ch.toUpperCase() : ch];
  if (L) return { w: L.w, strokes: L.s.map(st => st.map(p => p.slice())) };
  if (PUNCT[ch]) return { w: PUNCT[ch].w, strokes: PUNCT[ch].s.map(st => st.map(p => p.slice())) };
  return { w: 0.5, strokes: [], unknown: ch.trim() !== '' };
}

// 문장 → 줄 단위 배치. 어절 단위로 줄을 바꾸고, 한 어절이 줄보다 길면 글자 단위로 자른다.
export function layoutText(text, opt = {}) {
  const { track = 0.25, space = 0.6, leading = 0.45, maxWidth = Infinity } = opt;
  const lines = [];
  for (const para of String(text).split(/\n|\//)) {
    let cur = [], curW = 0;
    const flush = () => { lines.push({ glyphs: cur, width: Math.max(0, curW) }); cur = []; curW = 0; };
    const words = para.split(/\s+/).filter(Boolean);
    for (const word of words) {
      const gs = [...word].map(ch => ({ ch, ...glyph(ch) }));
      const ww = gs.reduce((a, g) => a + g.w, 0) + track * (gs.length - 1);
      const add = cur.length ? space : 0;
      if (cur.length && curW + add + ww > maxWidth) flush();
      if (ww > maxWidth) {   // 긴 어절: 글자 단위로 넘긴다
        for (const g of gs) {
          const a = cur.length ? track : 0;
          if (cur.length && curW + a + g.w > maxWidth) flush();
          g.x = curW + (cur.length ? track : 0); cur.push(g); curW = g.x + g.w;
        }
        continue;
      }
      let x = curW + (cur.length ? space : 0);
      for (const g of gs) { g.x = x; cur.push(g); x += g.w + track; }
      curW = x - track;
    }
    if (cur.length) flush();
  }
  const width = lines.reduce((a, l) => Math.max(a, l.width), 0);
  const height = lines.length ? lines.length + (lines.length - 1) * leading : 0;
  lines.forEach((l, i) => { l.y = i * (1 + leading); });
  return { lines, width, height };
}

// 배치 결과 → 절대 좌표 획 목록 (글자 순서 = 쓰는 순서). 각 획에 몇 번째 글자인지(item) 붙인다.
export function strokesOf(layout, { x = 0, y = 0, size = 1, align = 'center' } = {}) {
  const out = [];
  let item = 0;
  for (const line of layout.lines) {
    const ox = align === 'center' ? (layout.width - line.width) / 2 : 0;
    for (const g of line.glyphs) {
      for (const s of g.strokes) out.push({ item, pts: s.map(([px, py]) => [x + (ox + g.x + px) * size, y + (line.y + py) * size]) });
      if (g.strokes.length) item++;
    }
  }
  return out;
}
