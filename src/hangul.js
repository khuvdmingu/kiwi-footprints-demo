function place(strokes, [x0, y0, x1, y1]) {
  const w = x1 - x0, h = y1 - y0;
  return strokes.map(s => s.map(([x, y]) => [x0 + x * w, y0 + y * h]));
}

export function consonant(name) {
  if (PAIR[name]) {
    const [a, b] = PAIR[name];
    return [...place(CONS[a], [0, 0, 0.47, 1]), ...place(CONS[b], [0.53, 0, 1, 1])];
  }
  return CONS[name] ? CONS[name].map(s => s.map(p => p.slice())) : null;
}

export function decompose(ch) {
  const c = ch.codePointAt(0) - 0xac00;
  if (c < 0 || c > 11171) return null;
  return { cho: CHO[Math.floor(c / 588)], jung: JUNG[Math.floor((c % 588) / 28)], jong: JONG[c % 28] };
}

export function syllableStrokes(ch) {
  const d = decompose(ch);
  if (!d) return null;
  const t = vowelType(d.jung);
  const L = LAYOUT[t + (d.jong ? 'J' : '')];
  const out = [...place(consonant(d.cho), L.cho)];
  if (t === 'V') out.push(...place(VV[d.jung], L.v));
  else if (t === 'H') out.push(...place(HV[d.jung], L.h));
  else { const [h, v] = MIX[d.jung]; out.push(...place(HV[h], L.h), ...place(VV[v], L.v)); }
  if (d.jong) out.push(...place(consonant(d.jong), PAIR[d.jong] ? JONG_TWO : JONG_ONE));
  return out;
}

// 홀로 쓴 자모 (ㅋㅋ, ㅠㅠ 같은)
function jamoStrokes(ch) {
  if (CONS[ch] || PAIR[ch]) return place(consonant(ch), PAIR[ch] ? [0.05, 0.12, 0.95, 0.88] : [0.15, 0.12, 0.85, 0.88]);
  const t = vowelType(ch);
  if (t === 'V') return place(VV[ch], [0.2, 0.05, 0.8, 0.95]);
  if (t === 'H') return place(HV[ch], [0.05, 0.2, 0.95, 0.85]);
  if (t === 'M') { const [h, v] = MIX[ch]; return [...place(HV[h], [0, 0.3, 0.68, 0.9]), ...place(VV[v], [0.68, 0.05, 1, 0.95])]; }
  return null;
}

