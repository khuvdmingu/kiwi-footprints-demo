// beach3d/water/surface.js — 물결 면: 빛·굴절·빛 그물이 함께 보는 잔물결의 기울기
//  사용자 2026-11-23: "빛의 반짝임이 너무 작다보니까 자글거린다 … 지금 맵의 느낌이 젤다의 전설 같은 그래픽 풍인데, 그런것을 고려해봐"
//
//  앞 구조는 잔 노이즈의 기울기에 날카로운 반사광을 얹었다. 화소보다 잔 기울기는 프레임마다 다른 화소에 걸려 빛이 자글거린다.
//  여기서는 방향이 조금씩 다른 물결 여섯 겹(파장 17~95u)의 기울기를 식으로 바로 낸다 (긴 것 둘 + 짧은 것 넷):
//   · 화소보다 훨씬 굵은 물결뿐이라 자글거리지 않고, 반사광이 물결 면 하나하나에 크고 느리게 맺힌다 (그림풍)
//   · 기울기가 매끄러워서, 그 기울기로 꺾인 빛이 바닥에 모이고 퍼지는 것(빛 그물)을 그대로 계산할 수 있다 (shade.js)
//  물결은 뭍 쪽(−y)으로 다가오고, 하나는 물가를 따라 옆으로 흐른다. 느린 노이즈로 박자를 흩어 같은 무늬가 되풀이되지 않는다.

// BEACH_GLSL 뒤에 붙인다 (vnoise 를 쓴다). q = 그림 자리(u), 돌려주는 값 = 기울기(가로, 세로)
export const SURFACE_GLSL = /* glsl */ `
  // 긴 물결 둘 (파장 95u·60u) — 반사광은 이것(과 너울)만 본다.
  //  빛 조각의 폭은 물결 파장의 1/10 쯤이다(기울기가 그만큼 천천히 변한다) → 긴 물결이어야 빛 조각이 크고 느리게 맺힌다
  vec2 chopLongG(vec2 q, float t) {
    float w = (vnoise(q / 31. + vec2(0., t * .03)) - .5) * 5.;   // 곳마다 박자가 조금씩 다르다
    vec2 g = vec2(-.1, .995) * .16 * cos((-.1 * q.x + .995 * q.y) * .066 + t * .7 + w * .7 + 3.3);
    g += vec2(.18, .98) * .2 * cos((.18 * q.x + .98 * q.y) * .105 + t * .9 + w);
    return g * (.6 + .8 * vnoise(q / 60. + vec2(t * .01, 0.)));   // 잔잔한 데와 이는 데가 천천히 옮겨 다닌다
  }
  // 짧은 물결 넷 (파장 17~37u, 하나는 물가를 따라 옆으로) — 굴절·빛 그물·음영에 더한다
  vec2 chopShortG(vec2 q, float t) {
    float w = (vnoise(q / 31. + vec2(0., t * .03)) - .5) * 5.;
    vec2 g = vec2(-.34, .94) * .17 * cos((-.34 * q.x + .94 * q.y) * .17 + t * 1.2 + w * 1.3 + 1.7);
    g += vec2(.5, .87) * .14 * cos((.5 * q.x + .87 * q.y) * .26 + t * 1.5 - w * .8 + 4.1);
    g += vec2(-.7, .71) * .1 * cos((-.7 * q.x + .71 * q.y) * .37 + t * 1.9 + w * .6 + 2.6);
    g += vec2(.94, .34) * .08 * cos((.94 * q.x + .34 * q.y) * .31 + t * .7 + 5.2);
    return g * (.6 + .8 * vnoise(q / 60. + vec2(t * .01, 0.)));
  }
`;
