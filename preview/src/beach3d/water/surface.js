// beach3d/water/surface.js — 물결 면: 빛·굴절·빛 그물이 함께 보는 잔물결의 기울기
//  사용자 2026-11-23: "현재 물결은 너무 이상해.. 기름 같아." (그 앞: "반짝임이 너무 작다보니까 자글거린다 · 젤다의 전설 같은 그래픽 풍")
//
//  잔물결은 식으로 그리지 않고, 이음새 없는 물결 그림(normals.js) 두 장을 서로 다른 크기·방향·빠르기로 흘려 겹친다.
//   · 그림이라 그래픽 카드가 화면 칸 크기에 맞춰 걸러 준다(밉맵) → 잔물결이 있어도 자글거리지 않는다
//   · 크기가 다른 물결 수십 개가 섞여 있어 면이 매끈하지 않다 → 빛이 굵은 띠로 구불거리지 않는다(기름처럼 보이지 않는다)
//   · 두 장의 크기(64u·37u)가 서로 나눠떨어지지 않고 방향이 달라 같은 무늬가 되풀이돼 보이지 않는다
//  큰 너울(model.js swell)은 따로 높이의 차분으로 구해 이 위에 더한다 (shade.js).

// BEACH_GLSL 뒤에 붙인다. q = 그림 자리(u), 돌려주는 값 = 기울기(가로, 세로), 제곱평균 약 1
export const SURFACE_GLSL = /* glsl */ `
  uniform sampler2D uWaveN;   // 물결 그림 — 기울기를 RG 에 담았다 (normals.js, 0~1 ↔ −3~+3)
  vec2 waveTex(vec2 uv, float bias) { return (texture(uWaveN, uv, bias).rg - .5) * 6.; }
  //  bias: 0 = 잔물결까지 (반짝임) · 2 쯤 = 굵은 결만 부드럽게 (물속 굴절·빛 그물) — 그림 속 물결 모양을 잘게 구기지 않게
  vec2 ripplesG(vec2 q, float t, float bias) {
    vec2 a = waveTex(q / 64. + vec2(.011, -.019) * t, bias);                  // 큰 장: 뭍 쪽으로 천천히
    mat2 R = mat2(.8, .6, -.6, .8);                                     // 작은 장은 37° 돌려서 — 두 장의 결이 엇갈린다
    vec2 b = waveTex(R * q / 37. + vec2(-.016, -.027) * t, bias) * R;         // (돌린 자리에서 읽은 기울기를 다시 제자리 방향으로)
    return (a * .62 + b * .48) * (.75 + .5 * vnoise(q / 90. + vec2(t * .01, 0.)));   // 잔잔한 데와 이는 데가 천천히 옮겨 다닌다
  }
`;
